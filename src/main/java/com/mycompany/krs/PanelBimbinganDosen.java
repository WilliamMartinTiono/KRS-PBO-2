    private void loadTabelBimbingan() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(new String[]{"NIM", "Nama Mahasiswa", "Status KRS"}, 0);
        tblBimbingan.setModel(model);
        
        try {
            Database db = new Database();
            // Cari Periode
            java.sql.ResultSet rsPeriode = db.readDBSafe("SELECT id_periode FROM periode WHERE status_krs = 'Buka' LIMIT 1");
            if (rsPeriode != null && rsPeriode.next()) {
                idPeriodeAktif = rsPeriode.getString("id_periode");
            } else {
                return; // Berhenti jika tidak ada periode
            }

            // Cari Data Bimbingan
            String nidn = Login.getUserLogin();
            String sql = "SELECT m.nim, m.nama_mhs, COALESCE(k.status_validasi, 'Belum Isi') AS status_krs " +
                         "FROM mahasiswa m LEFT JOIN krs_header k ON m.nim = k.nim AND k.id_periode = ? " +
                         "WHERE m.id_dosen_wali = ? ORDER BY m.nama_mhs ASC";
            
            java.sql.ResultSet rs = db.readDBSafe(sql, idPeriodeAktif, nidn);
            while (rs != null && rs.next()) {
                model.addRow(new Object[]{rs.getString("nim"), rs.getString("nama_mhs"), rs.getString("status_krs")});
            }
        } catch (Exception e) {
            System.err.println("Gagal load tabel bimbingan: " + e.getMessage());
        }
    }
