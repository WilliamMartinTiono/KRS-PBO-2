    private void btnCetakKrsMhsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCetakKrsMhsActionPerformed
        // TODO add your handling code here:
        // 1. Validasi Baris Tabel (Pencegah ArrayIndexOutOfBoundsException)
        int row = tblBimbingan.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih salah satu mahasiswa dari tabel terlebih dahulu!");
            return;
        }

        // 2. Ambil NIM dari kolom ke-0 pada baris yang dipilih
        String nimTerpilih = tblBimbingan.getValueAt(row, 0).toString();

        // 3. Validasi Keamanan Variabel Periode Aktif
        // (Pastikan variabel idPeriodeAktif sudah diisi oleh fungsi loadTabelBimbingan())
        if (idPeriodeAktif == null || idPeriodeAktif.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Tidak ada periode aktif atau sistem gagal memuat periode.");
            return;
        }

        try {
            // 4. Cek Koneksi Database
            Database db = new Database();
            if (db.getConnection() == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "GAGAL: Koneksi Database terputus!");
                return;
            }

            // 5. Siapkan Parameter Jasper (TRIPLE-LOCK SECURITY)
            java.util.HashMap<String, Object> parameter = new java.util.HashMap<>();
            parameter.put("p_nim", nimTerpilih); // Dari pilihan tabel UI
            parameter.put("p_id_periode", idPeriodeAktif); // Dari state sistem
            parameter.put("p_nidn_dosen", Login.getUserLogin()); // OTORITAS MUTLAK DARI SESI LOGIN
            
            // 6. Cari Lokasi File JRXML
            java.io.File file = new java.io.File("src/main/java/com/mycompany/krs/CetakKrsBimbingan.jrxml");
            
            if (!file.exists()) {
                file = new java.io.File("src/com/mycompany/krs/CetakKrsBimbingan.jrxml");
            }
            
            if (!file.exists()) {
                javax.swing.JOptionPane.showMessageDialog(this, "GAGAL: File CetakKrsBimbingan.jrxml tidak ditemukan!");
                return;
            }
            
            // 7. Proses Compile & Baca File
            java.io.InputStream fileJrxml = new java.io.FileInputStream(file);
            net.sf.jasperreports.engine.JasperReport jasperReport = net.sf.jasperreports.engine.JasperCompileManager.compileReport(fileJrxml);
            
            // 8. Isi Laporan dengan Data
            net.sf.jasperreports.engine.JasperPrint jasperPrint = net.sf.jasperreports.engine.JasperFillManager.fillReport(jasperReport, parameter, db.getConnection());
            
            // 9. Cegah Laporan Kosong
            if (jasperPrint.getPages().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Dokumen kosong! Mahasiswa ini belum mengambil matkul atau bukan bimbingan Anda.");
                return;
            }
            
            // 10. Tampilkan Layar Pratinjau (Preview PDF)
            net.sf.jasperreports.view.JasperViewer.viewReport(jasperPrint, false);

        } catch (Exception e) {
            String namaError = e.toString();
            String barisError = (e.getStackTrace().length > 0) ? e.getStackTrace()[0].toString() : "Tidak diketahui";
            javax.swing.JOptionPane.showMessageDialog(this, "Terjadi Error Detail:\n" + namaError + "\n\nLokasi: " + barisError);
        }
    }//GEN-LAST:event_btnCetakKrsMhsActionPerformed


